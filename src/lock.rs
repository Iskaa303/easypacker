//! Easypacker.lock generation — resolves Easypacker.toml against
//! Modrinth/CurseForge and pins exact files, download urls and hashes.
//! Regenerated on every run; never edit by hand (cargo-style).

use crate::api::types::{DepKind, Dependency, Platform};
use crate::api::{
    CurseForgeClient, CurseForgeFileInfo, ModrinthClient, ModrinthProjectInfo, ModrinthVersionInfo,
};
use crate::config::Config;
use crate::project::{CATEGORIES, Manifest, ModSpec, is_latest, tstr};
use color_eyre::eyre::{Result, bail};
use serde::Deserialize;
use std::collections::{BTreeMap, HashSet};
use std::fmt::Write as _;
use std::path::Path;
use std::sync::Arc;

pub const LOCK_FILE: &str = "Easypacker.lock";
const LOCK_HEADER: &str = "# This file is automatically @generated by Easypacker.\n# It is not intended for manual editing.\n";

struct Lock {
    minecraft: String,
    loader: String,
    targets: Vec<String>,
    mod_: Vec<LockEntry>,
    resourcepack: Vec<LockEntry>,
    datapack: Vec<LockEntry>,
    shader: Vec<LockEntry>,
}

struct LockEntry {
    id: String,
    name: String,
    version: String,
    modrinth: Option<LockModrinth>,
    curseforge: Option<LockCurseForge>,
}

struct LockModrinth {
    slug: String,
    project_id: String,
    version_id: String,
    /// Modrinth's own version name (may differ from curseforge's).
    version: String,
    filename: String,
    url: Option<String>,
    size: u64,
    hashes: Option<LockHashes>,
    /// ids this version depends on.
    dependencies: Vec<LockDep>,
}

struct LockCurseForge {
    project_id: i64,
    file_id: i64,
    /// `CurseForge`'s own version name (may differ from modrinth's).
    version: String,
    filename: String,
    url: Option<String>,
    size: u64,
    hashes: Option<LockHashes>,
    /// ids this file depends on.
    dependencies: Vec<LockDep>,
    /// curseforge slug, used to cross-lookup the modrinth counterpart.
    slug: String,
}

struct LockHashes {
    sha1: Option<String>,
    sha512: Option<String>,
    md5: Option<String>,
}

#[derive(Clone)]
struct LockDep {
    id: String,
    optional: bool,
    /// Declared incompatible with the parent: never pinned, but reported when
    /// the other side is in the pack anyway.
    incompatible: bool,
}

impl LockHashes {
    fn new(sha1: Option<String>, sha512: Option<String>, md5: Option<String>) -> Option<Self> {
        if sha1.is_none() && sha512.is_none() && md5.is_none() {
            None
        } else {
            Some(Self { sha1, sha512, md5 })
        }
    }
}

/// The fields each platform pin are the same everywhere a version/file is
/// turned into a lock row (main entries, cross-lookups, dependency rows),
/// so the construction lives here exactly once.
impl LockModrinth {
    fn from_version(project: &ModrinthProjectInfo, v: &ModrinthVersionInfo) -> Self {
        Self {
            slug: project.slug.clone(),
            project_id: project.id.clone(),
            version_id: v.id.clone(),
            version: v.name.clone(),
            filename: v.filename.clone(),
            url: v.url.clone(),
            size: v.size,
            hashes: LockHashes::new(v.sha1.clone(), v.sha512.clone(), None),
            dependencies: deps_from(&v.dependencies),
        }
    }
}

impl LockCurseForge {
    fn from_file(mod_id: i32, f: &CurseForgeFileInfo, slug: String) -> Self {
        Self {
            project_id: i64::from(mod_id),
            file_id: i64::from(f.id),
            version: f.display_name.clone(),
            filename: f.file_name.clone(),
            url: cf_download_url(f),
            size: f.file_length,
            hashes: LockHashes::new(f.sha1.clone(), None, f.md5.clone()),
            dependencies: deps_from(&f.dependencies),
            slug,
        }
    }
}

/// Required + optional dependency edges, as lock rows understand them.
/// Dependency edges as lock rows understand them. Incompatible relations are
/// kept too (the resolver reports conflicts with them) but never pinned.
fn deps_from(deps: &[Dependency]) -> Vec<LockDep> {
    deps.iter()
        .filter(|d| {
            d.kind == DepKind::Required
                || d.kind == DepKind::Optional
                || d.kind == DepKind::Incompatible
        })
        .map(|d| LockDep {
            id: d.project_id.clone(),
            optional: d.kind == DepKind::Optional,
            incompatible: d.kind == DepKind::Incompatible,
        })
        .collect()
}

/// Find the counterpart file whose sha1 matches `want` (names differ between
/// modrinth and curseforge). Falls back to the first (latest) file when the
/// wanted side has no sha1 or no file matches — e.g. the wanted version
/// doesn't exist on the counterpart platform.
fn cf_file_matching<'a>(
    files: &'a [CurseForgeFileInfo],
    want: Option<&str>,
) -> Option<&'a CurseForgeFileInfo> {
    want.map_or_else(
        || files.first(),
        |w| {
            files
                .iter()
                .find(|f| f.sha1.as_deref().is_some_and(|s| s.eq_ignore_ascii_case(w)))
        },
    )
}

fn mr_version_matching<'a>(
    versions: &'a [ModrinthVersionInfo],
    want: Option<&str>,
) -> Option<&'a ModrinthVersionInfo> {
    want.map_or_else(
        || versions.first(),
        |w| {
            versions
                .iter()
                .find(|v| v.sha1.as_deref().is_some_and(|s| s.eq_ignore_ascii_case(w)))
        },
    )
}

/// `CurseForge` download URL. The API sometimes returns `download_url` as null,
/// but the CDN path is deterministic from the file id and name.
fn cf_download_url(f: &CurseForgeFileInfo) -> Option<String> {
    f.download_url.clone().or_else(|| {
        Some(format!(
            "https://edge.forgecdn.net/files/{}/{}/{}",
            f.id / 1000,
            f.id % 1000,
            f.file_name
        ))
    })
}

/// Outcome of one lockfile rebuild. Warnings are returned instead of printed
/// so the caller decides where they go (stderr for the CLI, an in-TUI status
/// line for the TUI — the alternate screen must not be scribbled on).
pub struct Report {
    pub resolved: usize,
    pub failed: usize,
    pub warnings: Vec<String>,
}

/// Read-only view of Easypacker.lock for the lookups that only need a few
/// fields (known ids, pinned version). Parsed with serde instead of walking
/// `toml::Value` by hand.
#[derive(Deserialize, Default)]
struct LockToml {
    #[serde(default, rename = "mod")]
    mod_: Vec<LockEntryToml>,
    #[serde(default)]
    resourcepack: Vec<LockEntryToml>,
    #[serde(default)]
    datapack: Vec<LockEntryToml>,
    #[serde(default)]
    shader: Vec<LockEntryToml>,
}

#[derive(Deserialize)]
struct LockEntryToml {
    #[serde(default)]
    version: Option<String>,
    #[serde(default)]
    modrinth: Option<LockMrToml>,
    #[serde(default)]
    curseforge: Option<LockCfToml>,
}

#[derive(Deserialize)]
struct LockMrToml {
    #[serde(default)]
    slug: Option<String>,
}

#[derive(Deserialize)]
struct LockCfToml {
    #[serde(default)]
    project_id: Option<i64>,
}

impl LockToml {
    fn read(dir: &Path) -> Option<Self> {
        toml::from_str(&std::fs::read_to_string(dir.join(LOCK_FILE)).ok()?).ok()
    }

    fn entries(&self) -> impl Iterator<Item = &LockEntryToml> {
        self.mod_
            .iter()
            .chain(&self.resourcepack)
            .chain(&self.datapack)
            .chain(&self.shader)
    }
}

/// Collect the project ids present in an existing lockfile, so the search
/// results can mark deps that are in the pack even when they're only in the
/// lockfile (not in the manifest). Returns (modrinth slugs, curseforge ids).
pub fn read_known_ids(
    dir: &Path,
) -> (
    std::collections::HashSet<String>,
    std::collections::HashSet<i64>,
) {
    let mut slugs = std::collections::HashSet::new();
    let mut cf_ids = std::collections::HashSet::new();
    let Some(lock) = LockToml::read(dir) else {
        return (slugs, cf_ids);
    };
    for entry in lock.entries() {
        if let Some(slug) = entry.modrinth.as_ref().and_then(|m| m.slug.clone()) {
            slugs.insert(slug);
        }
        if let Some(pid) = entry.curseforge.as_ref().and_then(|c| c.project_id) {
            cf_ids.insert(pid);
        }
    }
    (slugs, cf_ids)
}

/// Find the version string of a project in the existing lockfile, matched by
/// modrinth slug or curseforge project id. Used to mark the added file in
/// file-browse for lockfile-only deps.
pub fn read_lock_version(
    dir: &Path,
    modrinth_slug: Option<&str>,
    curseforge_id: Option<i64>,
) -> Option<String> {
    let lock = LockToml::read(dir)?;
    for entry in lock.entries() {
        let slug_match = modrinth_slug
            .is_some_and(|s| entry.modrinth.as_ref().and_then(|m| m.slug.as_deref()) == Some(s));
        let cf_match = curseforge_id
            .is_some_and(|id| entry.curseforge.as_ref().and_then(|c| c.project_id) == Some(id));
        if (slug_match || cf_match)
            && let Some(v) = &entry.version
        {
            return Some(v.clone());
        }
    }
    None
}

/// Resolve every manifest entry and rewrite Easypacker.lock. The lockfile is
/// purely derived from the TOML manifest: deps not present in the manifest
/// resolve to the highest matching version; deps the player pinned (via the
/// dependency popup, which writes them into the manifest) resolve to the
/// pinned version. UI actions never edit the lockfile directly.
/// `generate` is one linear pipeline (resolve manifest entries, then deps,
/// then render); splitting it into helpers would only scatter the flow.
#[allow(clippy::too_many_lines)]
pub async fn generate(dir: &Path, cfg: &Config) -> Result<Report> {
    // One rebuild at a time per process: the TUI starts one in the background
    // while a write action may start another, and both would race on the file.
    static REGEN: tokio::sync::Mutex<()> = tokio::sync::Mutex::const_new(());
    let _guard = REGEN.lock().await;

    let manifest = Manifest::load(dir)?;
    let proj = &manifest.project;

    let mut targets: Vec<String> = proj
        .platforms
        .iter()
        .map(|p| p.to_lowercase())
        .filter(|p| p == "modrinth" || p == "curseforge")
        .collect();
    targets.sort_unstable();
    targets.dedup();
    if targets.is_empty() {
        targets.push("modrinth".into());
    }
    let want_mr = targets.iter().any(|t| t == "modrinth");
    let want_cf = targets.iter().any(|t| t == "curseforge");

    let mut warnings: Vec<String> = Vec::new();
    let cf = if want_cf {
        let key = cfg.get_api_key(None, Some(dir));
        if key.is_err() {
            warnings.push("no CurseForge API key configured — CurseForge pins skipped".into());
        }
        key.ok().map(|k| Arc::new(CurseForgeClient::new(&k)))
    } else {
        None
    };

    let mut set = tokio::task::JoinSet::new();
    let mut requested = 0usize;
    for (cat, class_id) in CATEGORIES {
        for (id, spec) in manifest.cat(cat).iter() {
            requested += 1;
            let id = id.clone();
            let spec = spec.clone();
            let mc = proj.minecraft.clone();
            let loader = proj.loader.clone();
            let cf = cf.clone();
            let want_cf = cf.is_some();
            set.spawn(async move {
                let (entry, warnings) = resolve_entry(
                    cat, class_id, &id, &spec, &mc, &loader, want_mr, want_cf, cf,
                )
                .await;
                (cat, id, entry, warnings)
            });
        }
    }

    let (mut resolved, mut failed) = (BTreeMap::new(), 0usize);
    while let Some(joined) = set.join_next().await {
        match joined {
            Ok((cat, id, Ok(entry), entry_warnings)) => {
                warnings.extend(
                    entry_warnings
                        .into_iter()
                        .map(|w| format!("{cat}/{id}: {w}")),
                );
                resolved.insert((cat, id), entry);
            }
            Ok((cat, id, Err(e), _)) => {
                failed += 1;
                warnings.push(format!("{cat}/{id}: {e}"));
            }
            Err(e) => {
                failed += 1;
                warnings.push(format!("resolver task failed: {e}"));
            }
        }
    }

    // Don't clobber a good lockfile when everything failed (e.g. offline).
    if requested > 0 && resolved.is_empty() {
        bail!("all {requested} entries failed to resolve; keeping existing lockfile");
    }

    let resolved_count = resolved.len();
    let manifest_ids: HashSet<String> = manifest
        .mods
        .keys()
        .chain(manifest.resourcepacks.keys())
        .chain(manifest.datapacks.keys())
        .chain(manifest.shaders.keys())
        .cloned()
        .collect();

    // Resolve dependencies (cargo-style): each manifest entry declares dep
    // ids; unresolved ones become their own lock rows, transitively.
    let dep_entries = resolve_dependencies(
        &mut resolved,
        &manifest_ids,
        DepContext {
            mc: &proj.minecraft,
            loader: &proj.loader,
            want_mr,
            want_cf,
            cf: cf.clone(),
        },
        &mut warnings,
    )
    .await;

    let (mut mods, mut resourcepacks, mut datapacks, mut shaders) =
        (Vec::new(), Vec::new(), Vec::new(), Vec::new());
    for ((cat, _), entry) in resolved {
        match cat {
            "mod" => mods.push(entry),
            "resourcepack" => resourcepacks.push(entry),
            "datapack" => datapacks.push(entry),
            _ => shaders.push(entry),
        }
    }
    mods.extend(dep_entries);

    let lock = Lock {
        minecraft: proj.minecraft.clone(),
        loader: proj.loader.clone(),
        targets,
        mod_: mods,
        resourcepack: resourcepacks,
        datapack: datapacks,
        shader: shaders,
    };

    let text = render(&lock);
    // Writing an identical file would only churn its mtime (a lockfile is
    // tracked in git, and the TUI may rebuild it on every start).
    let path = dir.join(LOCK_FILE);
    if std::fs::read_to_string(&path).is_ok_and(|old| old == text) {
        return Ok(Report {
            resolved: resolved_count,
            failed,
            warnings,
        });
    }
    std::fs::write(&path, text)?;

    Ok(Report {
        resolved: resolved_count,
        failed,
        warnings,
    })
}

type ResolveOut = (Result<LockEntry, String>, Vec<String>);

/// `resolve_entry` resolves both platforms plus both cross-lookups for one
/// manifest entry; the branches are siblings, not separable stages.
#[allow(clippy::too_many_lines)]
#[allow(clippy::too_many_arguments)]
async fn resolve_entry(
    cat: &'static str,
    class_id: i32,
    id: &str,
    spec: &ModSpec,
    mc: &str,
    loader: &str,
    want_mr: bool,
    want_cf: bool,
    cf: Option<Arc<CurseForgeClient>>,
) -> ResolveOut {
    let is_mod = cat == "mod";
    let mut warnings = Vec::new();
    let mut name: Option<String> = None;
    // `latest` means "newest matching", which the resolver already does with
    // no pin — drop the marker so the lock records the resolved version.
    let mut version_name: Option<String> = spec.shared_version().filter(|v| !is_latest(v));
    let mut mr_lock = None;
    let mut cf_lock = None;
    // Stash by-name resolution errors; only surface them if the hash
    // cross-lookup can't recover the counterpart platform.
    let mut mr_err: Option<String> = None;
    let mut cf_err: Option<String> = None;

    // Only query platforms the spec explicitly targets by name.
    let has_mr = spec.has_modrinth();
    let has_cf = spec.has_curseforge();
    let resolve_mr = want_mr && has_mr;
    let resolve_cf = want_cf && has_cf;

    if resolve_mr {
        match resolve_modrinth(id, spec, mc, loader, is_mod).await {
            Ok((title, vname, l)) => {
                name = Some(title);
                if version_name.is_none() {
                    version_name = Some(vname);
                }
                mr_lock = Some(l);
            }
            Err(e) => mr_err = Some(e),
        }
    }
    if resolve_cf && let Some(ref client) = cf {
        match resolve_curseforge(client, class_id, id, spec, mc, loader, is_mod).await {
            Ok((title, vname, l)) => {
                if name.is_none() || title != id {
                    name.get_or_insert(title);
                }
                if version_name.is_none() {
                    version_name = Some(vname);
                }
                cf_lock = Some(l);
            }
            Err(e) => cf_err = Some(e),
        }
    }

    // Cross-platform: whenever the pack targets a platform but its side is
    // still missing, try to attach the counterpart by matching the resolved
    // file's sha1 (names differ between modrinth and curseforge). Only for
    // specs that target BOTH platforms — an entry scoped to one platform
    // (e.g. `{ curseforge = {...} }` with no modrinth) stays on that
    // platform in the lockfile; the export layer moves its file into
    // overrides for the other target.
    if want_cf
        && has_mr
        && has_cf
        && cf_lock.is_none()
        && let Some(ref l) = mr_lock
        && let Some(ref client) = cf
        && let Ok(Some((mod_id, _))) = client.find_by_slug(&l.slug, Some(class_id)).await
    {
        match client
            .get_files(
                mod_id,
                if mc.is_empty() { None } else { Some(mc) },
                if is_mod && !loader.is_empty() {
                    Some(loader)
                } else {
                    None
                },
            )
            .await
        {
            Ok(files) => {
                let want = l.hashes.as_ref().and_then(|h| h.sha1.as_deref());
                if let Some(f) = cf_file_matching(&files, want) {
                    cf_lock = Some(LockCurseForge::from_file(mod_id, f, l.slug.clone()));
                }
            }
            Err(e) => warnings.push(format!("curseforge cross: {e}")),
        }
    }
    if want_mr
        && has_mr
        && has_cf
        && mr_lock.is_none()
        && let Some(ref l) = cf_lock
        && let Ok(project) = ModrinthClient::get_project(&l.slug).await
    {
        match ModrinthClient::get_versions(
            &l.slug,
            if mc.is_empty() { None } else { Some(mc) },
            if is_mod && !loader.is_empty() {
                Some(loader)
            } else {
                None
            },
        )
        .await
        {
            Ok(versions) => {
                let want = l.hashes.as_ref().and_then(|h| h.sha1.as_deref());
                if let Some(v) = mr_version_matching(&versions, want) {
                    mr_lock = Some(LockModrinth::from_version(&project, v));
                    if name.is_none() {
                        name = Some(project.title);
                    }
                    if version_name.is_none() {
                        version_name = Some(v.name.clone());
                    }
                }
            }
            Err(e) => warnings.push(format!("modrinth cross: {e}")),
        }
    }

    // A spec that targets curseforge but has no client (no API key
    // configured) fails with an actionable message instead of an empty one.
    if resolve_cf && cf.is_none() && cf_lock.is_none() {
        cf_err = Some(
            "curseforge: no API key configured — set --api-key, CURSEFORGE_API_KEY, \
             or a .env file in the project directory"
                .to_owned(),
        );
    }

    // Only warn about a failed by-name resolution if the counterpart side is
    // still missing (i.e. hash matching couldn't recover it either).
    if mr_lock.is_none()
        && let Some(e) = mr_err
    {
        warnings.push(e);
    }
    if cf_lock.is_none()
        && let Some(e) = cf_err
    {
        warnings.push(e);
    }

    if mr_lock.is_none() && cf_lock.is_none() {
        return (Err(warnings.join("; ")), warnings);
    }

    (
        Ok(LockEntry {
            id: id.to_owned(),
            name: name.unwrap_or_else(|| id.to_owned()),
            version: version_name.unwrap_or_default(),
            modrinth: mr_lock,
            curseforge: cf_lock,
        }),
        warnings,
    )
}

async fn resolve_modrinth(
    id: &str,
    spec: &ModSpec,
    mc: &str,
    loader: &str,
    is_mod: bool,
) -> Result<(String, String, LockModrinth), String> {
    let slug = spec.modrinth_slug(id);
    let loader_filter = if is_mod && !loader.is_empty() {
        Some(loader)
    } else {
        None
    };
    let mc_filter = if mc.is_empty() { None } else { Some(mc) };
    let (project, versions) = tokio::join!(
        ModrinthClient::get_project(&slug),
        ModrinthClient::get_versions(&slug, mc_filter, loader_filter),
    );
    let project = project.map_err(|e| format!("modrinth: {e}"))?;
    let versions = versions.map_err(|e| format!("modrinth: {e}"))?;
    let requested = spec.version_for(true).filter(|v| !is_latest(v));
    // No requested version => latest (API returns newest first).
    let v = versions
        .iter()
        .find(|v| {
            requested
                .as_ref()
                .is_none_or(|req| *req == v.name || *req == v.version_number || *req == v.id)
        })
        .ok_or_else(|| {
            format!(
                "modrinth: version \"{}\" not found for {slug}",
                requested.unwrap_or_default()
            )
        })?;
    let lock = LockModrinth::from_version(&project, v);
    Ok((project.title, v.name.clone(), lock))
}

async fn resolve_curseforge(
    client: &CurseForgeClient,
    class_id: i32,
    id: &str,
    spec: &ModSpec,
    mc: &str,
    loader: &str,
    is_mod: bool,
) -> Result<(String, String, LockCurseForge), String> {
    let (mod_id, title) = if let Some(pid) = spec.curseforge_project_id() {
        (
            i32::try_from(pid).map_err(|_| format!("curseforge: projectId {pid} out of range"))?,
            id.to_owned(),
        )
    } else {
        let slug = spec.curseforge_slug(id).unwrap_or_else(|| id.to_owned());
        client
            .find_by_slug(&slug, Some(class_id))
            .await
            .map_err(|e| format!("curseforge: {e}"))?
            .ok_or_else(|| format!("curseforge: no project with slug \"{slug}\""))?
    };
    let loader_filter = if is_mod && !loader.is_empty() {
        Some(loader)
    } else {
        None
    };
    let mc_filter = if mc.is_empty() { None } else { Some(mc) };
    let files = client
        .get_files(mod_id, mc_filter, loader_filter)
        .await
        .map_err(|e| format!("curseforge: {e}"))?;
    let requested = spec.version_for(false).filter(|v| !is_latest(v));
    let f = files
        .iter()
        .find(|f| {
            requested.as_ref().is_none_or(|req| {
                *req == f.display_name || *req == f.file_name || *req == f.id.to_string()
            })
        })
        .ok_or_else(|| {
            format!(
                "curseforge: version \"{}\" not found for {id}",
                requested.unwrap_or_default()
            )
        })?;
    Ok((
        title,
        f.display_name.clone(),
        LockCurseForge::from_file(mod_id, f, id.to_owned()),
    ))
}

/// Resolve a transitive dependency by Modrinth project id into a lock row.
/// Picks the highest matching version (the API returns newest first), and —
/// when the pack targets `CurseForge` too — tries to attach the counterpart
/// file so the dep is pinned on both platforms like any normal mod.
async fn resolve_dep_modrinth(
    dep_id: &str,
    mc: &str,
    loader: &str,
    want_cf: bool,
    cf: Option<Arc<CurseForgeClient>>,
    warnings: &mut Vec<String>,
) -> Result<LockEntry, String> {
    let loader_filter = if loader.is_empty() {
        None
    } else {
        Some(loader)
    };
    let mc_filter = if mc.is_empty() { None } else { Some(mc) };
    let (project, versions) = tokio::join!(
        ModrinthClient::get_project(dep_id),
        ModrinthClient::get_versions(dep_id, mc_filter, loader_filter),
    );
    let project = project.map_err(|e| format!("modrinth dep {dep_id}: {e}"))?;
    let versions = versions.map_err(|e| format!("modrinth dep {dep_id}: {e}"))?;
    let slug = project.slug.clone();
    let v = versions
        .first()
        .ok_or_else(|| format!("modrinth dep {dep_id}: version not found"))?;

    // Cross-platform: try to find the same mod on CurseForge, matching the
    // chosen modrinth file by sha1 (names may differ between platforms).
    // A missing counterpart is a warning, not a failure: the row is still
    // pinned on modrinth.
    let cf_lock = if want_cf && let Some(client) = cf.as_ref() {
        match client.find_by_slug(&slug, Some(6)).await {
            Ok(Some((mod_id, _))) => match client.get_files(mod_id, mc_filter, loader_filter).await
            {
                Ok(files) => cf_file_matching(&files, v.sha1.as_deref())
                    .map(|f| LockCurseForge::from_file(mod_id, f, slug.clone())),
                Err(e) => {
                    warnings.push(format!("curseforge files for {slug}: {e}"));
                    None
                }
            },
            Ok(None) => None,
            Err(e) => {
                warnings.push(format!("curseforge lookup for {slug}: {e}"));
                None
            }
        }
    } else {
        None
    };

    let mr_lock = LockModrinth::from_version(&project, v);
    Ok(LockEntry {
        id: slug.clone(),
        name: project.title,
        version: v.name.clone(),
        modrinth: Some(mr_lock),
        curseforge: cf_lock,
    })
}

/// Resolve a transitive dependency by `CurseForge` mod id into a lock row.
/// Picks the highest matching file, and — when the pack targets Modrinth
/// too — tries to attach the counterpart version.
async fn resolve_dep_curseforge(
    client: &CurseForgeClient,
    dep_id: i32,
    mc: &str,
    loader: &str,
    want_mr: bool,
    warnings: &mut Vec<String>,
) -> Result<LockEntry, String> {
    let (mod_id, title, slug) = client
        .get_mod(dep_id)
        .await
        .map_err(|e| format!("cf dep {dep_id}: {e}"))?;
    let loader_filter = if loader.is_empty() {
        None
    } else {
        Some(loader)
    };
    let mc_filter = if mc.is_empty() { None } else { Some(mc) };
    let mut files = client
        .get_files(mod_id, mc_filter, loader_filter)
        .await
        .map_err(|e| format!("cf dep {dep_id}: {e}"))?;
    // CF file metadata is inconsistent across projects (some don't tag the
    // loader / game version the way the filter expects). If the filtered
    // query came back empty, fall back to the full file list — the lockfile
    // pins by hash anyway, and a missing counterpart is better than failing.
    if files.is_empty() {
        files = client
            .get_files(mod_id, None, None)
            .await
            .map_err(|e| format!("cf dep {dep_id}: {e}"))?;
    }
    let f = files
        .first()
        .ok_or_else(|| format!("cf dep {dep_id}: version not found"))?;

    // Cross-platform: try to find the same mod on Modrinth, matching the
    // chosen curseforge file by sha1 (names may differ between platforms).
    let mr_lock = if want_mr {
        match ModrinthClient::get_project(&slug).await {
            Ok(project) => {
                match ModrinthClient::get_versions(&slug, mc_filter, loader_filter).await {
                    Ok(versions) => mr_version_matching(&versions, f.sha1.as_deref())
                        .map(|v| LockModrinth::from_version(&project, v)),
                    Err(e) => {
                        warnings.push(format!("modrinth versions for {slug}: {e}"));
                        None
                    }
                }
            }
            Err(_) => None,
        }
    } else {
        None
    };

    Ok(LockEntry {
        id: slug.clone(),
        name: title,
        version: f.display_name.clone(),
        modrinth: mr_lock,
        curseforge: Some(LockCurseForge::from_file(mod_id, f, slug)),
    })
}

/// What the dependency resolver needs to know about the pack.
struct DepContext<'a> {
    mc: &'a str,
    loader: &'a str,
    want_mr: bool,
    want_cf: bool,
    cf: Option<Arc<CurseForgeClient>>,
}

/// One dependency edge: the platform that declared it, the raw project id,
/// and whether the parent called it optional (optional deps are pinned only
/// when the player enabled them in the manifest).
#[derive(Clone, PartialEq, Eq, Hash)]
struct DepEdge {
    platform: Platform,
    id: String,
    optional: bool,
}

/// Resolve the full transitive dependency graph of the manifest entries into
/// lock rows (breadth-first, cycle-safe): each entry's required deps are
/// resolved, and their required deps too, until nothing new appears.
///
/// Optional deps are pinned only when the player enabled them — they're then
/// manifest entries and are resolved (with the player's pin) separately.
/// Required deps already in the manifest keep the player's pin: the manifest
/// always wins over the generated row. Incompatible relations are never
/// pinned, but are reported when the other side ends up in the pack.
async fn resolve_dependencies(
    resolved: &mut BTreeMap<(&'static str, String), LockEntry>,
    manifest_ids: &HashSet<String>,
    ctx: DepContext<'_>,
    warnings: &mut Vec<String>,
) -> Vec<LockEntry> {
    let mut queue: std::collections::VecDeque<DepEdge> = edges_of(resolved.values());
    if queue.is_empty() {
        return Vec::new();
    }
    // A malformed graph (every dep depending on every other) must not spin
    // forever; the visited set already stops cycles, this bounds the walk.
    let max = (2 * queue.len()).max(256);

    // raw id -> easypacker slug for every dep that resolved, so edges can be
    // rewritten to readable ids even for deps that don't become lock rows.
    let mut slug_of: std::collections::HashMap<(Platform, String), String> =
        std::collections::HashMap::new();
    let mut seen: HashSet<DepEdge> = HashSet::new();
    let mut out: Vec<LockEntry> = Vec::new();
    let mut out_slugs: HashSet<String> = HashSet::new();

    while let Some(edge) = queue.pop_front() {
        if !seen.insert(edge.clone()) {
            continue;
        }
        if seen.len() > max {
            warnings.push(format!(
                "dependency graph larger than {max} edges — stopping the walk here"
            ));
            break;
        }
        let Some(entry) = resolve_dep_edge(&edge, &ctx, warnings).await else {
            continue;
        };
        let slug = entry.id.clone();
        slug_of.insert((edge.platform, edge.id.clone()), slug.clone());
        // The manifest wins: a pinned manifest entry is never duplicated as a
        // generated row (and its own deps come from its own resolution).
        if manifest_ids.contains(&slug) {
            continue;
        }
        // An optional dep the player didn't enable is not in the pack, and
        // neither are its own deps.
        if edge.optional {
            continue;
        }
        // Walk this dep's own required deps (the transitive step).
        queue.extend(edges_of(std::iter::once(&entry)));
        if !out_slugs.insert(slug) {
            continue; // already added (reached through a different id)
        }
        out.push(entry);
    }

    // Rewrite every entry's dep edges: raw id -> slug, keeping only required
    // deps that are actually in the pack (manifest entry or generated row).
    let known: HashSet<String> = manifest_ids.iter().cloned().chain(out_slugs).collect();
    for e in resolved.values_mut() {
        rewrite_edges(e, &slug_of, &known);
    }
    for e in &mut out {
        rewrite_edges(e, &slug_of, &known);
    }

    // A declared-incompatible project that made it into the pack anyway is
    // worth telling the player about — it usually means a broken pairing.
    let mut conflicts: Vec<String> = Vec::new();
    for e in resolved.values().chain(out.iter()) {
        for deps in [
            e.modrinth.as_ref().map(|m| &m.dependencies),
            e.curseforge.as_ref().map(|c| &c.dependencies),
        ]
        .into_iter()
        .flatten()
        {
            for d in deps
                .iter()
                .filter(|d| d.incompatible && known.contains(&d.id))
            {
                conflicts.push(format!(
                    "{} is declared incompatible with {} — both are in the pack",
                    e.id, d.id
                ));
            }
        }
    }
    conflicts.sort();
    conflicts.dedup();
    warnings.extend(conflicts);

    // Stable order by id for reproducible lockfiles.
    out.sort_by(|a, b| a.id.cmp(&b.id));
    out
}

/// Every dependency edge declared by the given entries (required, optional
/// and incompatible), deduplicated in a stable order.
fn edges_of<'a>(
    entries: impl Iterator<Item = &'a LockEntry>,
) -> std::collections::VecDeque<DepEdge> {
    let mut edges: Vec<DepEdge> = Vec::new();
    for e in entries {
        for (platform, deps) in [
            (
                Platform::Modrinth,
                e.modrinth.as_ref().map(|p| p.dependencies.as_slice()),
            ),
            (
                Platform::CurseForge,
                e.curseforge.as_ref().map(|p| p.dependencies.as_slice()),
            ),
        ]
        .into_iter()
        .filter_map(|(p, d)| d.map(|d| (p, d)))
        {
            for d in deps.iter().filter(|d| !d.incompatible) {
                edges.push(DepEdge {
                    platform,
                    id: d.id.clone(),
                    optional: d.optional,
                });
            }
        }
    }
    edges.sort_by(|a, b| a.id.cmp(&b.id));
    edges.dedup();
    edges.into()
}

/// Resolve one edge into a lock row on its own platform, attaching the
/// counterpart platform by sha1 when the pack targets both.
async fn resolve_dep_edge(
    edge: &DepEdge,
    ctx: &DepContext<'_>,
    warnings: &mut Vec<String>,
) -> Option<LockEntry> {
    match edge.platform {
        Platform::Modrinth => {
            if !ctx.want_mr {
                return None;
            }
            match resolve_dep_modrinth(
                &edge.id,
                ctx.mc,
                ctx.loader,
                ctx.want_cf,
                ctx.cf.clone(),
                warnings,
            )
            .await
            {
                Ok(entry) => Some(entry),
                Err(e) => {
                    warnings.push(e);
                    None
                }
            }
        }
        Platform::CurseForge => {
            if !ctx.want_cf {
                return None;
            }
            let client = ctx.cf.as_ref()?;
            let Ok(mod_id) = edge.id.parse::<i32>() else {
                return None;
            };
            match resolve_dep_curseforge(client, mod_id, ctx.mc, ctx.loader, ctx.want_mr, warnings)
                .await
            {
                Ok(entry) => Some(entry),
                Err(e) => {
                    warnings.push(e);
                    None
                }
            }
        }
    }
}

/// Rewrite an entry's dependency ids from raw project ids to easypacker slugs,
/// keeping only deps that are actually in the pack (manifest entry or dep row)
/// AND required (optional deps never appear in the edge list).
fn rewrite_edges(
    e: &mut LockEntry,
    slug_of: &std::collections::HashMap<(Platform, String), String>,
    known: &HashSet<String>,
) {
    if let Some(mr) = &mut e.modrinth {
        rewrite_deps(&mut mr.dependencies, Platform::Modrinth, slug_of, known);
    }
    if let Some(cf) = &mut e.curseforge {
        rewrite_deps(&mut cf.dependencies, Platform::CurseForge, slug_of, known);
    }
}

/// Rewrite one dependency list from raw project ids to easypacker slugs,
/// keeping only required deps that are actually in the pack. Optional and
/// incompatible relations never become lock edges.
fn rewrite_deps(
    deps: &mut Vec<LockDep>,
    platform: Platform,
    slug_of: &std::collections::HashMap<(Platform, String), String>,
    known: &HashSet<String>,
) {
    *deps = deps
        .iter()
        .filter(|d| !d.optional && !d.incompatible)
        .map(|d| {
            let id = slug_of
                .get(&(platform, d.id.clone()))
                .cloned()
                .unwrap_or_else(|| d.id.clone());
            LockDep {
                id,
                optional: false,
                incompatible: false,
            }
        })
        .filter(|d| known.contains(&d.id))
        .collect();
}

/// The dependency ids a list pins (incompatible relations are not pins).
fn pinned_ids(deps: &[LockDep]) -> impl Iterator<Item = String> + '_ {
    deps.iter()
        .filter(|d| !d.incompatible)
        .map(|d| d.id.clone())
}

/// Render fields as a multi-line inline table (TOML 1.1), e.g.
/// `{
///    slug = "sodium",
///    ...
/// }` indented to `indent` levels.
fn inline_table(fields: &[String], indent: usize) -> String {
    let pad = "    ".repeat(indent);
    let body = fields
        .iter()
        .map(|f| format!("{pad}{f}"))
        .collect::<Vec<_>>()
        .join(",\n");
    format!("{{\n{body}\n{}}}", "    ".repeat(indent - 1))
}

fn render_hashes(h: &LockHashes, indent: usize) -> String {
    let mut fields = Vec::new();
    if let Some(s) = &h.sha1 {
        fields.push(format!("sha1 = {}", tstr(s)));
    }
    if let Some(s) = &h.sha512 {
        fields.push(format!("sha512 = {}", tstr(s)));
    }
    if let Some(s) = &h.md5 {
        fields.push(format!("md5 = {}", tstr(s)));
    }
    inline_table(&fields, indent)
}

fn render(lock: &Lock) -> String {
    let mut out = String::from(LOCK_HEADER);
    out.push_str("version = 1\n");
    writeln!(out, "minecraft = {}", tstr(&lock.minecraft)).unwrap();
    writeln!(out, "loader = {}", tstr(&lock.loader)).unwrap();
    let targets = lock
        .targets
        .iter()
        .map(|t| tstr(t))
        .collect::<Vec<_>>()
        .join(", ");
    writeln!(out, "targets = [{targets}]").unwrap();

    let categories: [(&str, &Vec<LockEntry>); 4] = [
        ("mod", &lock.mod_),
        ("resourcepack", &lock.resourcepack),
        ("datapack", &lock.datapack),
        ("shader", &lock.shader),
    ];
    for (cat, entries) in categories {
        for e in entries {
            writeln!(out, "\n[[{cat}]]").unwrap();
            writeln!(out, "id = {}", tstr(&e.id)).unwrap();
            writeln!(out, "name = {}", tstr(&e.name)).unwrap();
            // `version` is the shared pin; a platform only repeats its own
            // name when it differs from it (they usually don't).
            writeln!(out, "version = {}", tstr(&e.version)).unwrap();
            if let Some(mr) = &e.modrinth {
                let mut fields = vec![
                    format!("slug = {}", tstr(&mr.slug)),
                    format!("project_id = {}", tstr(&mr.project_id)),
                    format!("version_id = {}", tstr(&mr.version_id)),
                ];
                if mr.version != e.version {
                    fields.push(format!("version = {}", tstr(&mr.version)));
                }
                fields.push(format!("filename = {}", tstr(&mr.filename)));
                if let Some(url) = &mr.url {
                    fields.push(format!("url = {}", tstr(url)));
                }
                fields.push(format!("size = {}", mr.size));
                if let Some(h) = &mr.hashes {
                    fields.push(format!("hashes = {}", render_hashes(h, 2)));
                }
                writeln!(out, "modrinth = {}", inline_table(&fields, 1)).unwrap();
            }
            if let Some(cf) = &e.curseforge {
                let mut fields = vec![
                    format!("project_id = {}", cf.project_id),
                    format!("file_id = {}", cf.file_id),
                ];
                if cf.version != e.version {
                    fields.push(format!("version = {}", tstr(&cf.version)));
                }
                fields.push(format!("filename = {}", tstr(&cf.filename)));
                if let Some(url) = &cf.url {
                    fields.push(format!("url = {}", tstr(url)));
                }
                fields.push(format!("size = {}", cf.size));
                if let Some(h) = &cf.hashes {
                    fields.push(format!("hashes = {}", render_hashes(h, 2)));
                }
                writeln!(out, "curseforge = {}", inline_table(&fields, 1)).unwrap();
            }
            // Dependency edges (cargo-style): list the ids this entry pins,
            // one per line like Cargo.lock.
            let deps = collect_dep_ids(e);
            if !deps.is_empty() {
                writeln!(out, "dependencies = [").unwrap();
                for d in &deps {
                    writeln!(out, "    {},", tstr(d)).unwrap();
                }
                writeln!(out, "]").unwrap();
            }
        }
    }
    out
}

/// Resolve ids declared by this entry across whichever platforms it pins.
fn collect_dep_ids(e: &LockEntry) -> Vec<String> {
    let mut ids: Vec<String> = Vec::new();
    if let Some(mr) = &e.modrinth {
        ids.extend(pinned_ids(&mr.dependencies));
    }
    if let Some(cf) = &e.curseforge {
        ids.extend(pinned_ids(&cf.dependencies));
    }
    ids.sort();
    ids.dedup();
    ids
}

