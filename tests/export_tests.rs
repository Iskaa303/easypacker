#[test]
fn zip_roundtrip() {
    let bytes = zip_bytes(&[
        ("a.txt".into(), b"hello".to_vec()),
        ("dir/b.bin".into(), vec![1, 2, 3]),
    ])
    .unwrap();
    let mut archive = zip::ZipArchive::new(std::io::Cursor::new(bytes)).unwrap();
    assert_eq!(archive.len(), 2);
    let mut a = String::new();
    archive
        .by_name("a.txt")
        .unwrap()
        .read_to_string(&mut a)
        .unwrap();
    assert_eq!(a, "hello");
    let mut b = Vec::new();
    archive
        .by_name("dir/b.bin")
        .unwrap()
        .read_to_end(&mut b)
        .unwrap();
    assert_eq!(b, vec![1, 2, 3]);
}

/// Full curseforge export (mods only => no network downloads) produces a zip
/// with a valid manifest.json and no overrides.
#[tokio::test]
async fn curseforge_export_end_to_end() {
    let dir = std::env::temp_dir().join(format!("easypacker-export-{}", std::process::id()));
    std::fs::create_dir_all(&dir).unwrap();
    sample_manifest().save(&dir).unwrap();
    // Mod-only lock: mods become files[] entries, nothing gets downloaded.
    let lock_raw = LOCK_SAMPLE
        .lines()
        .take_while(|l| !l.starts_with("[[resourcepack]]"))
        .collect::<Vec<_>>()
        .join("\n");
    std::fs::write(dir.join(crate::lock::LOCK_FILE), lock_raw).unwrap();

    let pack = Manifest::load(&dir).unwrap();
    let lock = LockPack::load(&dir).unwrap();
    let http = reqwest::Client::new();
    let out = export_curseforge(
        &pack,
        &lock,
        "neoforge",
        "21.1.248",
        ExportSide::Client,
        &http,
    )
    .await
    .unwrap();
    assert_eq!(out.written, 1);
    assert_eq!(out.skipped, 0);

    let mut archive = zip::ZipArchive::new(std::io::Cursor::new(out.bytes)).unwrap();
    assert_eq!(archive.len(), 1);
    let mut manifest = String::new();
    archive
        .by_name("manifest.json")
        .unwrap()
        .read_to_string(&mut manifest)
        .unwrap();
    let v: Value = serde_json::from_str(&manifest).unwrap();
    assert_eq!(v["files"][0]["projectID"], 394_468);
    assert_eq!(v["files"][0]["fileID"], 12_345);
    assert_eq!(v["minecraft"]["modLoaders"][0]["id"], "neoforge-21.1.248");
    std::fs::remove_dir_all(&dir).ok();
}

/// Modrinth export: mods with a modrinth pin become files[]; a CF-only
/// resourcepack can't be referenced, so its download is attempted as an
/// override — the unreachable URL fails fast (127.0.0.1:1), lands in
/// warnings and counts as skipped. Fully offline.
#[tokio::test]
async fn modrinth_export_end_to_end() {
    let dir = std::env::temp_dir().join(format!("easypacker-export-mr-{}", std::process::id()));
    std::fs::create_dir_all(&dir).unwrap();
    sample_manifest().save(&dir).unwrap();
    std::fs::write(dir.join(crate::lock::LOCK_FILE), LOCK_SAMPLE).unwrap();

    let pack = Manifest::load(&dir).unwrap();
    let lock = LockPack::load(&dir).unwrap();
    let http = reqwest::Client::new();
    let out = export_modrinth(
        &pack,
        &lock,
        "neoforge",
        "21.1.248",
        ExportSide::Client,
        &http,
    )
    .await
    .unwrap();
    assert_eq!(out.written, 1); // only sodium has a modrinth pin
    assert_eq!(out.skipped, 1); // fresh-animations override download refused
    assert!(
        out.warnings
            .iter()
            .any(|w| w.contains("Fresh Animations") && w.contains("skipped")),
        "expected an override-download warning, got: {:?}",
        out.warnings
    );

    let mut archive = zip::ZipArchive::new(std::io::Cursor::new(out.bytes)).unwrap();
    assert_eq!(archive.len(), 1);
    let mut index = String::new();
    archive
        .by_name("modrinth.index.json")
        .unwrap()
        .read_to_string(&mut index)
        .unwrap();
    let v: Value = serde_json::from_str(&index).unwrap();
    assert_eq!(
        v["files"][0]["path"],
        "mods/sodium-neoforge-0.8.12+mc1.21.1.jar"
    );
    assert_eq!(v["files"][0]["hashes"]["sha512"], "bbb");
    assert_eq!(v["dependencies"]["neoforge"], "21.1.248");
    std::fs::remove_dir_all(&dir).ok();
}

