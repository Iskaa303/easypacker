/// Server exports drop client-only mods and client-only categories before
/// any network work; datapacks (server-side by default) stay in.
#[tokio::test]
async fn cf_server_export_drops_client_entries() {
    let dir = std::env::temp_dir().join(format!("easypacker-cfserver-{}", std::process::id()));
    std::fs::create_dir_all(&dir).unwrap();
    let pack = sided_manifest();
    pack.save(&dir).unwrap();
    let lock_raw = r#"version = 1
minecraft = "1.21.1"
loader = "neoforge"
targets = ["curseforge", "modrinth"]

[[mod]]
id = "sodium"
name = "Sodium"
curseforge = { project_id = 394468, file_id = 12345, filename = "sodium.jar" }

[[mod]]
id = "tfc"
name = "TerraFirmaCraft"
curseforge = { project_id = 302973, file_id = 54321, filename = "tfc.jar" }

[[resourcepack]]
id = "fresh-animations"
name = "Fresh Animations"
curseforge = {
    project_id = 557041,
    file_id = 5982607,
    filename = "FreshAnimations.zip",
    url = "http://127.0.0.1:1/FreshAnimations.zip"
}

[[datapack]]
id = "tfc-datapack"
name = "TFC Datapack"
curseforge = {
    project_id = 1,
    file_id = 1,
    filename = "tfc-dp.zip",
    url = "http://127.0.0.1:1/tfc-dp.zip"
}
"#;
    std::fs::write(dir.join(crate::lock::LOCK_FILE), lock_raw).unwrap();

    let pack = Manifest::load(&dir).unwrap();
    let lock = LockPack::load(&dir).unwrap();
    let http = reqwest::Client::new();
    let out = export_curseforge(
        &pack,
        &lock,
        "neoforge",
        "21.1.248",
        ExportSide::Server,
        &http,
    )
    .await
    .unwrap();
    // tfc -> files[]; sodium + resourcepack filtered; datapack download refused
    assert_eq!(out.written, 1);
    assert_eq!(out.skipped, 3);
    assert!(
        out.warnings.iter().any(|w| w.contains("TFC Datapack")),
        "datapacks must stay in server exports: {:?}",
        out.warnings
    );

    let mut archive = zip::ZipArchive::new(std::io::Cursor::new(out.bytes)).unwrap();
    let mut manifest = String::new();
    archive
        .by_name("manifest.json")
        .unwrap()
        .read_to_string(&mut manifest)
        .unwrap();
    let v: Value = serde_json::from_str(&manifest).unwrap();
    let files = v["files"].as_array().unwrap();
    assert_eq!(files.len(), 1);
    assert_eq!(files[0]["projectID"], 302_973);
    std::fs::remove_dir_all(&dir).ok();
}

/// Modrinth: a client-declared mod is dropped from server exports and marked
/// server-`unsupported` in client exports.
#[tokio::test]
async fn mr_export_respects_declared_sides() {
    let dir = std::env::temp_dir().join(format!("easypacker-mrside-{}", std::process::id()));
    std::fs::create_dir_all(&dir).unwrap();
    let pack = sided_manifest();
    pack.save(&dir).unwrap();
    let lock_raw = r#"version = 1
minecraft = "1.21.1"
loader = "neoforge"
targets = ["curseforge", "modrinth"]

[[mod]]
id = "sodium"
name = "Sodium"
modrinth = {
    slug = "sodium",
    project_id = "AANobbMI",
    version_id = "S3DUMfBo",
    filename = "sodium.jar",
    url = "http://127.0.0.1:1/sodium.jar",
    size = 1,
    hashes = { sha1 = "aaa", sha512 = "bbb" }
}

[[mod]]
id = "tfc"
name = "TerraFirmaCraft"
modrinth = {
    slug = "terrafirmacraft",
    project_id = "JaCEZUhg",
    version_id = "eBIfZlEM",
    filename = "tfc.jar",
    url = "http://127.0.0.1:1/tfc.jar",
    size = 2,
    hashes = { sha1 = "ccc", sha512 = "ddd" }
}
"#;
    std::fs::write(dir.join(crate::lock::LOCK_FILE), lock_raw).unwrap();

    let pack = Manifest::load(&dir).unwrap();
    let lock = LockPack::load(&dir).unwrap();
    let http = reqwest::Client::new();

    // Client export ships both, with sodium server-unsupported.
    let out = export_modrinth(
        &pack,
        &lock,
        "neoforge",
        "21.1.248",
        ExportSide::Client,
        &http,
    )
    .await
    .unwrap();
    assert_eq!(out.written, 2);
    let mut archive = zip::ZipArchive::new(std::io::Cursor::new(out.bytes)).unwrap();
    let mut index = String::new();
    archive
        .by_name("modrinth.index.json")
        .unwrap()
        .read_to_string(&mut index)
        .unwrap();
    let v: Value = serde_json::from_str(&index).unwrap();
    assert_eq!(v["files"].as_array().unwrap().len(), 2);
    let sodium = &v["files"][0];
    assert_eq!(sodium["env"]["client"], "required");
    assert_eq!(sodium["env"]["server"], "unsupported");

    // Server export drops the client-only mod.
    let out = export_modrinth(
        &pack,
        &lock,
        "neoforge",
        "21.1.248",
        ExportSide::Server,
        &http,
    )
    .await
    .unwrap();
    assert_eq!(out.written, 1);
    assert_eq!(out.skipped, 1);
    let mut archive = zip::ZipArchive::new(std::io::Cursor::new(out.bytes)).unwrap();
    let mut index = String::new();
    archive
        .by_name("modrinth.index.json")
        .unwrap()
        .read_to_string(&mut index)
        .unwrap();
    let v: Value = serde_json::from_str(&index).unwrap();
    let files = v["files"].as_array().unwrap();
    assert_eq!(files.len(), 1);
    assert_eq!(files[0]["path"], "mods/tfc.jar");
    std::fs::remove_dir_all(&dir).ok();
}

