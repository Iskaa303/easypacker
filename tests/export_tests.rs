#[test]
fn side_of_defaults_and_include() {
    let pack = sample_manifest();
    assert_eq!(side_of(&pack, "mod", "x"), Side::Both);
    assert_eq!(side_of(&pack, "resourcepack", "x"), Side::Client);
    assert_eq!(side_of(&pack, "shader", "x"), Side::Client);
    assert_eq!(side_of(&pack, "datapack", "x"), Side::Server);
    assert!(include(Side::Both, ExportSide::Client));
    assert!(include(Side::Client, ExportSide::Client));
    assert!(include(Side::Server, ExportSide::Client));
    assert!(include(Side::Both, ExportSide::Server));
    assert!(include(Side::Server, ExportSide::Server));
    assert!(!include(Side::Client, ExportSide::Server));
    assert_eq!(mod_env(Side::Both), ("required", "required"));
    assert_eq!(mod_env(Side::Client), ("required", "unsupported"));
    assert_eq!(mod_env(Side::Server), ("unsupported", "required"));
}

